export interface DataRow {
  sucursal: string;
  nombreApellido: string;
  usuario: string;
}

export async function fetchData(): Promise<DataRow[]> {
  const res = await fetch('/api/data');
  if (!res.ok) throw new Error(`Error al cargar datos: ${res.statusText}`);
  return res.json() as Promise<DataRow[]>;
}

export function getParsedData(rows: DataRow[]): DataRow[] {
  const excUsers = ['jia'];
  const excBranch = ['*', '000199', '000198', '199', '198'];
  return rows.filter(row =>
    !excUsers.includes(row.usuario.toLowerCase()) &&
    !excBranch.includes(row.sucursal)
  );
}

export interface GraphNode {
  id: string;
  label: string;
  type: 'sucursal' | 'usuario' | 'supervisor';
  group: number;
}

export interface GraphLink {
  source: string;
  target: string;
}

export function getGraphData(data: DataRow[]) {
  const nodes = new Map<string, GraphNode>();
  const links: GraphLink[] = [];

  const supervisors = ['eelizondo', 'jrusnak', 'hmoran', 'lejarque', 'bjorda', 'gastong', 'evidable', 'jrossini'];

  data.forEach((row) => {
    const branchId = `branch_${row.sucursal}`;
    if (!nodes.has(branchId)) {
      nodes.set(branchId, { id: branchId, label: row.sucursal, type: 'sucursal', group: 1 });
    }

    const userId = `user_${row.usuario}`;
    if (!nodes.has(userId)) {
      const isSupervisor = supervisors.includes(row.usuario.toLowerCase());
      nodes.set(userId, { id: userId, label: row.usuario, type: isSupervisor ? 'supervisor' : 'usuario', group: isSupervisor ? 3 : 2 });
    }

    links.push({ source: branchId, target: userId });
  });

  return {
    nodes: Array.from(nodes.values()),
    links,
  };
}
